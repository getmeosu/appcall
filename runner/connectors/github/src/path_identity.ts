import table from "./path_identity_fields.json";
import { pathValueFields, pathValueViolation } from "./path_values";

// FIX-SEGMENT-2: GitHub login and repository-name validation for every op whose REST path
// carries an owner / org / username (or equivalent login: assignee, targetUser,
// templateOwner) or a repository name (repo, repoName, templateRepo).
//
// FIX-SEGMENT stopped "." / ".." / "\" / blank from reshaping a path, but a single-segment
// field could still carry "/" (owner "a/b" -> /repos/a/b/...), and nothing bounded logins
// or repo names. These are validated at dispatch, before any handler runs, so a rejected
// value makes 0 fetches. Valid values are untouched (requests stay byte-identical).
//
// path_identity_fields.json lists op -> field -> class. It is generated by sentinel
// discovery through the registry (linus's probe method: a field whose sentinel reaches the
// request pathname) and cross-checked against the manifest route metadata; the test
// path_identity.test.ts re-derives it, so a new op cannot silently skip validation.
//
// Rules:
// - login: ASCII letters, digits and hyphens, 1-39 characters. Hyphens may appear anywhere,
//   including at the edges and doubled: GitHub's sign-up rule (single hyphens, none at the
//   edges) is newer than some still-valid legacy logins (linus, FIX-SEGMENT-2 amend).
//   + Enterprise Managed Users (owner and user fields): GitHub appends "_<shortcode>"
//     (3-8 alphanumerics) to every managed user login, total still <= 39
//     (docs.github.com/enterprise-cloud@latest/admin/managing-iam/iam-configuration-reference/username-considerations-for-external-authentication).
//   + GitHub App bot accounts (user fields only): "<login>[bot]", e.g. dependabot[bot].
//   Underscores are accepted only in the EMU form; ".", "/", whitespace and every other
//   character are rejected.
// - repository name: [A-Za-z0-9._-], 1-100 characters, not "." or "..".

export type IdentityClass = "owner" | "org" | "user" | "repo";

const FIELDS = table as Record<string, Record<string, IdentityClass>>;

const LOGIN = /^[A-Za-z0-9-]+$/;
const EMU_LOGIN = /^[A-Za-z0-9-]+_[A-Za-z0-9]{3,8}$/;
const BOT_LOGIN = /^([A-Za-z0-9-]+)\[bot\]$/;
const REPO_NAME = /^[A-Za-z0-9._-]+$/;

export const LOGIN_MAX = 39;
export const REPO_MAX = 100;

export function isGitHubLogin(value: string, cls: Exclude<IdentityClass, "repo">): boolean {
  if (value.length <= LOGIN_MAX && LOGIN.test(value)) return true;
  if (cls !== "org" && value.length <= LOGIN_MAX && EMU_LOGIN.test(value)) return true;
  if (cls === "user") {
    const bot = BOT_LOGIN.exec(value);
    if (bot && bot[1]!.length <= LOGIN_MAX) return true;
  }
  return false;
}

export function isGitHubRepoName(value: string): boolean {
  return value.length <= REPO_MAX && REPO_NAME.test(value) && value !== "." && value !== "..";
}

/** Throws a validation error for an invalid login / repository-name value; returns it unchanged otherwise. */
export function requireGitHubIdentity(value: string, field: string, cls: IdentityClass): string {
  if (cls === "repo") {
    if (!isGitHubRepoName(value)) {
      throw new Error(`${field} must be a GitHub repository name: letters, digits, ".", "-" or "_", at most ${REPO_MAX} characters, not "." or ".." (no "/")`);
    }
    return value;
  }
  if (!isGitHubLogin(value, cls)) {
    throw new Error(`${field} must be a GitHub login: letters, digits and hyphens, at most ${LOGIN_MAX} characters (no "/", "." or whitespace)`);
  }
  return value;
}

export function pathIdentityFields(op: string): Readonly<Record<string, IdentityClass>> | undefined {
  return FIELDS[op];
}

/** Returns the first violation for an op's input, or null. Absent / null fields and blank strings are left to the handler and to the FIX-SEGMENT-3 blank guard; the value is checked as given (no trimming). */
export function pathIdentityViolation(op: string, input: unknown): Error | null {
  const fields = FIELDS[op];
  if (!fields || typeof input !== "object" || input === null || Array.isArray(input)) return null;
  const record = input as Record<string, unknown>;
  for (const [field, cls] of Object.entries(fields)) {
    const value = record[field];
    if (value === undefined || value === null) continue;
    if (typeof value !== "string") return new Error(`${field} must be a string`);
    // FIX-SEGMENT-3: no trimming. " octocat " is rejected (path_values.ts rejects it first).
    if (value.trim().length === 0) continue;
    try {
      requireGitHubIdentity(value, field, cls);
    } catch (error) {
      return error as Error;
    }
  }
  return null;
}

type Handler = (input: any) => unknown;

/**
 * Wraps every registered github action (hand-written and compiled declarative) so path values
 * (FIX-SEGMENT-3: non-blank, no surrounding whitespace) and login / repo fields are validated
 * before the handler runs. A violation is returned as a rejected
 * promise, the same shape as the handlers' own input errors (the runner maps it to
 * INVALID_ACTION_INPUT). Valid input reaches the original handler unchanged.
 */
export function withGitHubPathIdentityGuard<T extends { actions?: Record<string, Record<string, Handler>> }>(input: T): T {
  const github = input.actions?.github;
  if (!github) return input;
  const guarded: Record<string, Handler> = {};
  for (const [op, handler] of Object.entries(github)) {
    if (!FIELDS[op] && !pathValueFields(op)) {
      guarded[op] = handler;
      continue;
    }
    guarded[op] = (value: unknown) => {
      // FIX-SEGMENT-3 blank / whitespace guard first, then the FIX-SEGMENT-2 login / repo rule.
      const violation = pathValueViolation(op, value) ?? pathIdentityViolation(op, value);
      if (violation) return Promise.reject(violation);
      return handler(value);
    };
  }
  return { ...input, actions: { ...input.actions, github: guarded } };
}
