import table from "./path_value_fields.json";

// FIX-SEGMENT-3: blank and whitespace-padded values for every input field that reaches a GitHub
// REST request path (required and optional), plus the lookup keys of the three "one of" read ops
// whose bad values used to end as an upstream ok:false instead of an input error.
//
// - A blank value ("", " ", "\t") collapsed routes: an optional trailing segment was dropped
//   (git.refs.list ref "" -> /git/refs) or produced "/labels/". Present means non-blank: an
//   optional trailing segment is dropped only when the field is omitted (undefined).
// - Leading or trailing whitespace (" octocat ") was sent as %20octocat%20, or silently trimmed
//   by a few handlers. Both are rejected now; nothing is normalized.
//
// path_value_fields.json (op -> field -> class) is generated by sentinel discovery through the
// registry over every top-level string field (required and optional) and cross-checked with the
// manifest routes; test/path_values.test.ts re-derives it. Classes:
// - path: the value is interpolated into the request path.
// - selector: a lookup key of deployments.get / releases.assets.get / discussions.* (query or
//   GraphQL variable). Same rule: non-blank, no surrounding whitespace.
// - text-selector: discussions.get title (a free-text match). Non-blank only.
// Violations are rejected at dispatch, before the handler runs: 0 fetches, INVALID_ACTION_INPUT.

export type PathValueClass = "path" | "selector" | "text-selector";

const FIELDS = table as Record<string, Record<string, PathValueClass>>;

export function pathValueFields(op: string): Readonly<Record<string, PathValueClass>> | undefined {
  return FIELDS[op];
}

/** Throws unless value is a non-blank string with no leading or trailing whitespace (numbers pass: some id fields accept both). */
export function requirePathValue(value: unknown, field: string): string {
  if (typeof value !== "string" || value.trim().length === 0) throw new Error(`${field} is required and must not be blank`);
  if (value !== value.trim()) throw new Error(`${field} must not have leading or trailing whitespace`);
  return value;
}

export function pathValueViolation(op: string, input: unknown): Error | null {
  const fields = FIELDS[op];
  if (!fields || typeof input !== "object" || input === null || Array.isArray(input)) return null;
  const record = input as Record<string, unknown>;
  for (const [field, cls] of Object.entries(fields)) {
    if (!(field in record)) continue;
    const value = record[field];
    if (value === undefined) continue;
    if (typeof value === "number" && Number.isFinite(value)) continue;
    if (typeof value !== "string") return new Error(`${field} must be a string`);
    if (value.trim().length === 0) return new Error(`${field} must not be blank (omit it instead)`);
    if (cls !== "text-selector" && value !== value.trim()) return new Error(`${field} must not have leading or trailing whitespace`);
  }
  return null;
}
