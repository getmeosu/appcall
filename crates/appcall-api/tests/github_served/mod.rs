//! Shared runtime-served bookkeeping for the GitHub end-to-end tests.
//!
//! Each e2e owns one source in `runner/connectors/github/fixtures/runtime-served.json`:
//! `poll` (github_poll_e2e.rs) and `webhook` (event_routes.rs, the WH-1 signed-webhook e2e).
//! `slugs` is the union of the sources. From that union this module renders, keeping each
//! file's formatting:
//!
//! - `runtime-served.json` itself,
//! - the `runtimeServed` scalars (and the count) in `fixtures/composio-coverage.json`,
//! - the `runtimeServed:` scalar on each slug's line of `src/trigger_map.ts`.
//!
//! With `APPCALL_GITHUB_SERVED_WRITE=1` the files are written; otherwise each must already
//! match, so a stale file fails the e2e. The TS trigger_map test asserts all three agree.
use serde_json::{json, Value};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::{Path, PathBuf},
};

fn github() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../runner/connectors/github")
}

fn served_path() -> PathBuf {
    github().join("fixtures/runtime-served.json")
}

fn coverage_path() -> PathBuf {
    github().join("fixtures/composio-coverage.json")
}

fn trigger_map_path() -> PathBuf {
    github().join("src/trigger_map.ts")
}

/// Replace the value of the first `"key": <scalar>` at or after `from`.
fn set_scalar(text: &mut String, from: usize, key: &str, value: &str) {
    let needle = format!("\"{key}\": ");
    let start = from + text[from..].find(&needle).unwrap() + needle.len();
    let end = start + text[start..].find([',', '\n', '}']).unwrap();
    text.replace_range(start..end, value);
}

/// The sources recorded so far; a file from before sources existed counts as `poll` only.
fn sources() -> BTreeMap<String, BTreeSet<String>> {
    let doc: Value = serde_json::from_slice(&std::fs::read(served_path()).unwrap()).unwrap();
    match doc.get("sources").and_then(Value::as_object) {
        Some(sources) => sources
            .iter()
            .map(|(k, v)| (k.clone(), serde_json::from_value(v.clone()).unwrap()))
            .collect(),
        None => BTreeMap::from([(
            "poll".to_owned(),
            serde_json::from_value(doc["slugs"].clone()).unwrap(),
        )]),
    }
}

fn served_file(sources: &BTreeMap<String, BTreeSet<String>>, union: &BTreeSet<String>) -> String {
    let doc = json!({
        "_note": "Generated by the GitHub e2e tests with APPCALL_GITHUB_SERVED_WRITE=1 (crates/appcall-api/tests/github_served/mod.rs). sources.poll: github_poll_e2e.rs, each slug's event reached webhook_events and was dispatched through webhook_outbox in a real api + runner + worker run against a mocked GitHub. sources.webhook: event_routes.rs (WH-1), each slug was emitted for an X-Hub-Signature-256 verified delivery that went through the real Bun runner and was persisted to webhook_events with a webhook_outbox row. slugs is the union.",
        "sources": sources,
        "slugs": union,
    });
    serde_json::to_string_pretty(&doc).unwrap() + "\n"
}

fn served_coverage(served: &BTreeSet<String>) -> String {
    let mut text = std::fs::read_to_string(coverage_path()).unwrap();
    let triggers = text.find("\"triggers\": {").unwrap();
    let counts = triggers + text[triggers..].find("\"counts\": {").unwrap();
    set_scalar(
        &mut text,
        counts,
        "runtimeServed",
        &served.len().to_string(),
    );
    let slugs: Vec<String> = serde_json::from_str::<Value>(&text).unwrap()["triggers"]["slugs"]
        .as_object()
        .unwrap()
        .keys()
        .cloned()
        .collect();
    for slug in slugs {
        let at = triggers + text[triggers..].find(&format!("\"{slug}\": {{")).unwrap();
        let value = if served.contains(&slug) {
            "true"
        } else {
            "false"
        };
        set_scalar(&mut text, at, "runtimeServed", value);
    }
    text
}

/// Rewrite only the `runtimeServed: <bool>` scalar on each `  SLUG: { ... }` entry line.
fn served_trigger_map(served: &BTreeSet<String>) -> String {
    let text = std::fs::read_to_string(trigger_map_path()).unwrap();
    let mut out = String::with_capacity(text.len());
    for line in text.split_inclusive('\n') {
        let slug = line
            .strip_prefix("  ")
            .and_then(|rest| rest.split_once(": { class: "))
            .map(|(slug, _)| slug);
        match slug {
            Some(slug) if line.contains("runtimeServed: ") => {
                let value = served.contains(slug);
                out.push_str(
                    &line
                        .replacen("runtimeServed: true", "runtimeServed: \u{0}", 1)
                        .replacen("runtimeServed: false", "runtimeServed: \u{0}", 1)
                        .replacen('\u{0}', if value { "true" } else { "false" }, 1),
                );
            }
            _ => out.push_str(line),
        }
    }
    out
}

/// Record `slugs` as the `source` e2e's proven set, then write or check the three files.
pub fn record(source: &str, slugs: &BTreeSet<String>) {
    let mut sources = sources();
    sources.insert(source.to_owned(), slugs.clone());
    let union: BTreeSet<String> = sources.values().flatten().cloned().collect();
    let files = [
        (served_path(), served_file(&sources, &union)),
        (coverage_path(), served_coverage(&union)),
        (trigger_map_path(), served_trigger_map(&union)),
    ];
    let write = std::env::var("APPCALL_GITHUB_SERVED_WRITE").as_deref() == Ok("1");
    for (path, expected) in files {
        if write {
            std::fs::write(&path, expected).unwrap();
        } else {
            assert_eq!(
                std::fs::read_to_string(&path).unwrap(),
                expected,
                "{} is stale; rerun with APPCALL_GITHUB_SERVED_WRITE=1",
                path.display()
            );
        }
    }
}
